// ─── Public API ───────────────────────────────────────────────────────────────

/** Recipe replacing `symbol` of `packageName`, if one exists and its preconditions hold. */
export function recipeFor(packageName: string, symbol: UsedSymbol): EvictionRecipe | undefined {
  const recipe = RECIPES.find((r) =>
    r.packageName === packageName && r.matches.some(([m, n]) => m === symbol.module && n === symbol.name));
  if (!recipe) { return undefined; }
  if (recipe.maxArity !== undefined) {
    const passedAsValue = symbol.references > symbol.callArities.length;
    if (passedAsValue || symbol.callArities.some((a) => a > recipe.maxArity!)) { return undefined; }
  }
  return recipe;
}

/**
 * A package can be evicted by recipe only when every symbol it is used for at
 * runtime has a recipe whose preconditions hold at every call site.
 */
export function lookup(packageName: string, runtimeSymbols: UsedSymbol[], usesWholeModule: boolean): EvictionInfo {
  const covered: string[] = [];
  const uncovered: string[] = [];
  for (const s of runtimeSymbols) {
    const label = s.name === 'default' ? s.module : s.name;
    (recipeFor(packageName, s) ? covered : uncovered).push(label);
  }
  if (usesWholeModule) { uncovered.push('*'); }
  const available = covered.length > 0 && uncovered.length === 0;
  return { available, strategy: available ? 'recipe' : null, covered, uncovered };
}

export function getRecipe(packageName: string, symbolName: string): EvictionRecipe | undefined {
  return RECIPES.find((r) => r.packageName === packageName && r.symbolName === symbolName);
}
